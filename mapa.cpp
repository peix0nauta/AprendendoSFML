void Mapa::desenhar(sf::RenderWindow& window) {
    for (int i = 0; i < LINHAS; i++) {       
        for (int j = 0; j < COLUNAS; j++) {     
            
            if (grade[i][j] == 100) {
                chao.setFillColor(sf::Color::Green); // Parede
                chao.setPosition({j * larguraBloco, i * alturaBloco});
                window.draw(chao);
            }
            else if (grade[i][j] == 001) {
                ceu.setFillColor(sf::Color::Blue); // Parede
                ceu.setPosition({j * larguraBloco, i * alturaBloco});
                window.draw(ceu);
            }

        }
    }
}


bool Mapa::Colisao(sf::Vector2f posicao){

    int coluna = static_cast<int>(posicao.x / larguraBloco);
    int linha = static_cast<int>(posicao.y / alturaBloco);

    if (linha < 0 || linha >= LINHAS || coluna < 0 || coluna >= COLUNAS) {
        return true; 
    }
 
    return grade[linha][coluna]==100;
}


